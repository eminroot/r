// Rebuild objects recursively so every auth sub-tree is deeply localized.
// Non-string values (including any future Clerk formatter functions) are retained.
function translateTree<T>(value: T): T {
  if (typeof value === 'string') return (azPhrases[value] ?? value) as T;
  if (Array.isArray(value)) return value.map(item => translateTree(item)) as T;
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, translateTree(item)]),
    ) as T;
  }
  return value;
}

