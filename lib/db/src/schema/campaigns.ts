import { pgTable, text, integer, serial, boolean, timestamp } from "drizzle-orm/pg-core";
export const campaigns = pgTable("bd_campaigns", {
  id: serial("id").primaryKey(),
  ownerId: text("owner_id").notNull(),
  title: text("title").notNull(),
  company: text("company").notNull(),
  logoUrl: text("logo_url").notNull().default(""),
  description: text("description").notNull(),
  category: text("category").notNull(),
  tags: text("tags").array().notNull().default([]),
  reward: text("reward").notNull(),
  rewardValue: integer("reward_value").notNull().default(0),
  method: text("method").notNull(),
  slots: integer("slots").notNull(),
  filledSlots: integer("filled_slots").notNull().default(0),
  status: text("status").notNull().default("active"),
  instructions: text("instructions").notNull(),
  productUrl: text("product_url").notNull(),
  screeningQuestions: text("screening_questions").array().notNull(),
  minTrust: integer("min_trust").notNull().default(0),
  autoApprove: boolean("auto_approve").notNull().default(false),
  autoApproveTrust: integer("auto_approve_trust").notNull().default(0),
  secretHash: text("secret_hash"),
  rewardCodes: text("reward_codes").array().notNull().default([]),
  featured: boolean("featured").notNull().default(false),
  demo: boolean("demo").notNull().default(false),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});
